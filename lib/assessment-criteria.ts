const wfmeOptions: CriterionGroup[] = wfmeSections.map((section, index) => ({
  label: `${index + 1}. ${section.title}`,
  options: section.topics.flatMap(([title, count], topicIndex) =>
    Array.from({ length: count }, (_, questionIndex) => {
      const sourceCode = `${index + 1}.${topicIndex + 1}.${questionIndex + 1}`;
      const value = `W${sourceCode}`;
      const description = `${title} · ข้อ ${questionIndex + 1}`;
      return { value, sourceCode, description, label: `${value} — ${description}` };
    }),
  ),
}));

const aunOptions: CriterionGroup[] = aunSections.map((section, index) => ({
  label: `${index + 1}. ${section.title}`,
  options: section.topics.map((description, topicIndex) => {
    const sourceCode = `${index + 1}.${topicIndex + 1}`;
    const value = `A${sourceCode}-1`;
    return { value, sourceCode, description, label: `${value} — ${description}` };
  }),
}));

export const assessmentCriteria: Record<AssessmentFramework, CriterionGroup[]> = {
  WFME: wfmeOptions,
  AUN: aunOptions,
};

const criterionCodes = {
  WFME: new Set(
    wfmeOptions.flatMap((group) => group.options.map((item) => item.value)),
  ),
  AUN: new Set(
    aunOptions.flatMap((group) => group.options.map((item) => item.value)),
  ),
};

export function isValidCriterion(
  criterion: string,
  framework: AssessmentFramework,
) {
  return criterionCodes[framework].has(criterion);
}
